test('JS: a shebang and the top comment stay; templates, regexes and URLs are not comments', () => {
  const text = cs(
    '#!/usr/bin/env node',
    '// The tool.',
    "import { a } from './a.mjs';",
    "const url = 'http://example.com'; // where",
    'const t = `x ${ y ? "//" : `in ${z}` } // still template`;',
    'const r = /\\/\\/[/]/g; // a comment',
    '// @ts-ignore',
    'const half = a / 2 / 3;',
    '/* old',
    '   lines */',
    'export { half };',
  );
  assert.equal(once(text, 'js'), cs(
    '#!/usr/bin/env node',
    '// The tool.',
    "import { a } from './a.mjs';",
    "const url = 'http://example.com';",
    'const t = `x ${ y ? "//" : `in ${z}` } // still template`;',
    'const r = /\\/\\/[/]/g;',
    '// @ts-ignore',
    'const half = a / 2 / 3;',
    'export { half };',
  ));
});

test('Python: # comments go, # in strings and tool markers stay, a docstring that was a whole body leaves pass', () => {
  const text = cs(
    '"""The tool."""',
    'import os',
    "s = '# not a comment'  # a comment",
    'x = 1  # noqa: E501',
    '# A note.',
    'def f():',
    '    """Only a docstring."""',
    'def g():',
    '    """A docstring."""',
    '    return 1',
  );
  assert.equal(once(text, 'python'), cs(
    '"""The tool."""',
    'import os',
    "s = '# not a comment'",
    'x = 1  # noqa: E501',
    'def f():',
    '    pass',
    'def g():',
    '    return 1',
  ));
});

test('a file with nothing to take out comes back the same', () => {
  const text = cs('// The file.', 'class A { }');
  assert.equal(purge(text, 'csharp'), text);
});
