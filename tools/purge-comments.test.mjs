// The comment purge's tests (purge-comments.mjs): what goes, what stays, the blank lines left behind, the top comment, and that a second run changes nothing.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { purge, verify } from './purge-comments.mjs';

const cs = (...rows) => rows.join('\n') + '\n';
const once = (text, language) => {
  const out = purge(text, language);
  assert.deepEqual(verify(text, out, language), []);
  assert.equal(purge(out, language), out, 'a second run changes nothing');
  return out;
};

test('C#: the top comment stays, line, trailing and doc comments go', () => {
  const text = cs(
    '// The file.',
    'using System;',
    '',
    'namespace Chem',
    '{',
    '    /// <summary>A thing.</summary>',
    '    public class A',
    '    {',
    '        // Why b is 1.',
    '        int b = 1; // trailing',
    '        int c = 2;',
    '    }',
    '}',
  );
  assert.equal(once(text, 'csharp'), cs(
    '// The file.',
    'using System;',
    '',
    'namespace Chem',
    '{',
    '    public class A',
    '    {',
    '        int b = 1;',
    '        int c = 2;',
    '    }',
    '}',
  ));
});

test('C#: // inside strings of every kind and in URLs stays', () => {
  const text = cs(
    '// The file.',
    'class A',
    '{',
    '    string a = "http://example.com"; // a link',
    '    string b = @"a ""quoted"" // still a string";',
    '    string c = $"{1} /* no */";',
    '    string d = """',
    '        // raw, not a comment',
    '        """;',
    "    char e = '/';",
    "    char f = '\"'; // a quote",
    '    string g = $"add {Url ?? $"http://127.0.0.1:{Port}/mcp"}"; // nested',
    '}',
  );
  assert.equal(once(text, 'csharp'), cs(
    '// The file.',
    'class A',
    '{',
    '    string a = "http://example.com";',
    '    string b = @"a ""quoted"" // still a string";',
    '    string c = $"{1} /* no */";',
    '    string d = """',
    '        // raw, not a comment',
    '        """;',
    "    char e = '/';",
    "    char f = '\"';",
    '    string g = $"add {Url ?? $"http://127.0.0.1:{Port}/mcp"}";',
    '}',
  ));
});

test('C#: a block comment over several lines goes whole, and one inside a line leaves the code tidy', () => {
  const text = cs(
    '// The file.',
    'class A',
    '{',
    '    /* one',
    '       two */',
    '    void F() { G(/* x */ 1, 2 /* y */); }',
    '    void H() { /* nothing */ }',
    '    int /* units */ k;',
    '}',
  );
  assert.equal(once(text, 'csharp'), cs(
    '// The file.',
    'class A',
    '{',
    '    void F() { G(1, 2); }',
    '    void H() { }',
    '    int k;',
    '}',
  ));
});

test('C#: preprocessor lines, pragmas, regions and analyser markers stay; their trailing comments go', () => {
  const text = cs(
    '// The file.',
    'class A',
    '{',
    '#region Parts',
    '#if UNITY_EDITOR // only in the Editor',
    '#pragma warning disable S1168 // empty is right',
    '    int a;',
    '#pragma warning restore S1168',
    '#endif',
    '#endregion',
    '    // ReSharper disable once InconsistentNaming',
    '    [System.Diagnostics.CodeAnalysis.SuppressMessage("x", "y", Justification = "a // reason")]',
    '    int B;',
    '}',
  );
  assert.equal(once(text, 'csharp'), cs(
    '// The file.',
    'class A',
    '{',
    '#region Parts',
    '#if UNITY_EDITOR',
    '#pragma warning disable S1168',
    '    int a;',
    '#pragma warning restore S1168',
    '#endif',
    '#endregion',
    '    // ReSharper disable once InconsistentNaming',
    '    [System.Diagnostics.CodeAnalysis.SuppressMessage("x", "y", Justification = "a // reason")]',
    '    int B;',
    '}',
  ));
  const generated = cs('// <auto-generated>', '// The file.', 'class A { }');
  assert.equal(once(generated, 'csharp'), generated);
});

test('C#: no blank lines doubled, none left after an opening brace or before a closing one', () => {
  const text = cs(
    '// The file.',
    'class A',
    '{',
    '    // The first part.',
    '',
    '    int a;',
    '',
    '    // The second part.',
    '',
    '    int b;',
    '    // Nothing after this.',
    '}',
  );
  assert.equal(once(text, 'csharp'), cs(
    '// The file.',
    'class A',
    '{',
    '    int a;',
    '',
    '    int b;',
    '}',
  ));
});

test('C#: a file whose only description is on its first type gets it as the top comment', () => {
  const text = cs(
    'using NUnit.Framework;',
    '',
    'namespace Chem.Tests',
    '{',
    '    /// <summary>',
    '    /// Acts and <see cref="World"/>, by <paramref name="x"/> &amp; more.',
    '    /// </summary>',
    '    [Category("Unit")]',
    '    public class ActTests',
    '    {',
    '    }',
    '}',
  );
  assert.equal(once(text, 'csharp'), cs(
    '// Acts and World, by x & more.',
    'using NUnit.Framework;',
    '',
    'namespace Chem.Tests',
    '{',
    '    [Category("Unit")]',
    '    public class ActTests',
    '    {',
    '    }',
    '}',
  ));
});

test('C#: a top comment and a summary on the first type: the summary goes', () => {
  const text = cs('using UnityEngine;', '', '// What the file is.', '', '/// <summary>The type.</summary>', 'public class A { }');
  assert.equal(once(text, 'csharp'), cs('using UnityEngine;', '', '// What the file is.', '', 'public class A { }'));
});

